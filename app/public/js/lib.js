  function createApi(tokenKey) {
    async function request(method, url, body, opts = {}) {
      const headers = { Accept: 'application/json' };
      const tok = localStorage.getItem(tokenKey);
      if (tok) headers.Authorization = `Bearer ${tok}`;
      let payload;
      if (body instanceof FormData) payload = body;
      else if (body !== undefined) { headers['Content-Type'] = 'application/json'; payload = JSON.stringify(body); }
      let res;
      try {
        res = await fetch(url, { method, headers, body: payload });
      } catch {
        throw Object.assign(new Error('No se pudo conectar con el servidor. Revisa tu conexión.'), { status: 0 });
      }
      if (opts.raw) {
        if (!res.ok) throw Object.assign(new Error('No se pudo descargar el archivo'), { status: res.status });
        return res;
      }
      let data = null;
      const text = await res.text();
      try { data = text ? JSON.parse(text) : null; } catch { data = null; }
      if (!res.ok) {
        const err = new Error((data && data.error) || `Error ${res.status}`);
        err.status = res.status;
        if (res.status === 401 && tok) {
          localStorage.removeItem(tokenKey);
          global.dispatchEvent(new CustomEvent('auth:expired'));
        }
        throw err;
      }
      return data;
    }
    return {
      get: (u, o) => request('GET', u, undefined, o),
      post: (u, b) => request('POST', u, b),
      put: (u, b) => request('PUT', u, b),
      patch: (u, b) => request('PATCH', u, b),
      del: (u, b) => request('DELETE', u, b),
    };
  }

