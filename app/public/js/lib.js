  function toast(msg, type = 'info', ms = 3200) {
    let wrap = document.querySelector('.toasts');
    if (!wrap) { wrap = document.createElement('div'); wrap.className = 'toasts'; wrap.setAttribute('aria-live', 'polite'); document.body.appendChild(wrap); }
    const el = document.createElement('div');
    el.className = `toast ${type}`;
    const ic = type === 'error' ? 'alert' : type === 'success' ? 'check' : 'info';
    el.innerHTML = `${icon(ic)}<span>${esc(msg)}</span>`;
    wrap.appendChild(el);
    setTimeout(() => { el.classList.add('leaving'); setTimeout(() => el.remove(), 220); }, ms);
  }

  function modal({ title, body, footer = '', size = '', onMount } = {}) {
    const bd = document.createElement('div');
    bd.className = 'modal-backdrop';
    bd.innerHTML = `<div class="modal ${size}" role="dialog" aria-modal="true" aria-label="${esc(title)}">
      <div class="modal-head"><h3>${esc(title)}</h3><button type="button" class="btn btn-ghost btn-icon btn-sm" data-close aria-label="Cerrar">${icon('close')}</button></div>
      <div class="modal-body">${body}</div>${footer ? `<div class="modal-foot">${footer}</div>` : ''}</div>`;
    const prevOverflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    document.body.appendChild(bd);
    const close = () => {
      bd.remove();
      document.body.style.overflow = prevOverflow;
      document.removeEventListener('keydown', onKey);
    };
    const onKey = (e) => { if (e.key === 'Escape') close(); };
    document.addEventListener('keydown', onKey);
    bd.addEventListener('mousedown', (e) => { if (e.target === bd) close(); });
    bd.querySelectorAll('[data-close]').forEach((b) => b.addEventListener('click', close));
    const el = bd.querySelector('.modal');
    if (onMount) onMount(el, close);
    const first = el.querySelector('input:not([type=hidden]), select, textarea');
    if (first) setTimeout(() => first.focus(), 30);
    return { el, close };
  }

  function confirmDialog(message, { title = 'Confirmar', okText = 'Confirmar', danger = false } = {}) {
    return new Promise((resolve) => {
      let done = false;
      const m = modal({
        title, size: 'sm',
        body: `<p>${esc(message)}</p>`,
        footer: `<button type="button" class="btn" data-close>Cancelar</button><button type="button" class="btn ${danger ? 'btn-danger' : 'btn-primary'}" data-ok>${esc(okText)}</button>`,
        onMount: (el, close) => {
          el.querySelector('[data-ok]').addEventListener('click', () => { done = true; close(); resolve(true); });
        },
      });
      const obs = new MutationObserver(() => { if (!document.body.contains(m.el)) { obs.disconnect(); if (!done) resolve(false); } });
      obs.observe(document.body, { childList: true });
    });
  }

  async function withLoading(btn, fn) {
    if (!btn) return fn();
    const html = btn.innerHTML;
    btn.disabled = true;
    btn.innerHTML = `<span class="spinner"></span>${btn.dataset.loading ? esc(btn.dataset.loading) : ''}`;
    try { return await fn(); } finally { btn.disabled = false; btn.innerHTML = html; }
  }

  function formData(form) {
    const out = {};
    for (const el of form.elements) {
      if (!el.name || el.disabled) continue;
      if (el.type === 'checkbox') out[el.name] = el.checked;
      else if (el.type === 'radio') { if (el.checked) out[el.name] = el.value; }
      else out[el.name] = el.value;
    }
    return out;
  }

  function debounce(fn, ms = 300) {
    let t;
    return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
  }

