  let moneyFmt = null;
  function setMoneyFormat(locale, currency) {
    fmtCfg = { locale: locale || 'es-PE', currency: currency || 'PEN' };
    try { moneyFmt = new Intl.NumberFormat(fmtCfg.locale, { style: 'currency', currency: fmtCfg.currency, minimumFractionDigits: 2 }); }
    catch { moneyFmt = new Intl.NumberFormat('es-PE', { style: 'currency', currency: 'PEN' }); }
  }
  setMoneyFormat();
  const money = (n) => moneyFmt.format(Number(n) || 0);
  const moneyShort = (n) => {
    try { return new Intl.NumberFormat(fmtCfg.locale, { style: 'currency', currency: fmtCfg.currency, notation: 'compact', maximumFractionDigits: 1 }).format(Number(n) || 0); }
    catch { return money(n); }
  };

  function parseDate(s) {
    if (!s) return null;
    // Las fechas de SQLite vienen en UTC "YYYY-MM-DD HH:MM:SS"
    return new Date(String(s).replace(' ', 'T') + (String(s).length <= 19 ? 'Z' : ''));
  }
  function fmtDate(s, withTime = false) {
    const d = parseDate(s);
    if (!d || isNaN(d)) return '';
    const o = { day: '2-digit', month: 'short', year: 'numeric' };
    if (withTime) Object.assign(o, { hour: '2-digit', minute: '2-digit' });
    return d.toLocaleString(fmtCfg.locale, o);
  }

